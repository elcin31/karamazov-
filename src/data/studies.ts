import chapterManifest from "./chapters.json";
import chapterData from "./chapters.json";

export type StudySection = {
  id: string;
  title: string;
  kind: "analysis" | "text-fact" | "research";
  paragraphs: string[];
  chapterIds: string[];
};
export type StudySource = { title: string; url: string; note: string };
export type Study = {
  id: string;
  title: string;
  subtitle: string;
  dek: string;
  chapterIds: string[];
  characterIds: string[];
  revealAt: string;
  sections: StudySection[];
  sources: StudySource[];
};
const sourceFor = (ids: string[]): StudySource[] => [
  ...ids.slice(0, 4).map((id) => {
    const c = chapterData.find((c) => c.id === id)!;
    return {
      title: `${c.book === 13 ? "Эпилог" : `Книга ${c.book}`}, глава ${c.chapter}. ${c.title}`,
      url: c.sourceUrl,
      note: "Первичный текст. Издание «Наука», 1991, т. 9–10; электронная транскрипция ilibrary.ru.",
    };
  }),
  {
    title: "Академический комментарий к «Братьям Карамазовым»",
    url: "https://rvb.ru/dostoevski/02comm/35_1.htm",
    note: "Г. М. Фридлендер, Е. И. Кийко, В. Е. Ветловская и другие. История замысла, литературные и религиозные контексты; не источник готовых выводов редакции.",
  },
  {
    title: "Братья Карамазовы — Викитека",
    url: "https://ru.wikisource.org/wiki/Братья_Карамазовы_(Достоевский)",
    note: "Дополнительный текстовый ориентир и структура произведения. Полный корпус сайта сохранён из указанного в первой ссылке источника.",
  },
];
const section = (
  id: string,
  title: string,
  chapterIds: string[],
  paragraphs: string[],
  kind: StudySection["kind"] = "analysis",
): StudySection => ({ id, title, chapterIds, paragraphs, kind });
const study = (value: Omit<Study, "sources">): Study => ({
  ...value,
  sources: sourceFor(value.chapterIds),
});

